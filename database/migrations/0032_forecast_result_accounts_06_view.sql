-- Source: dba.Forecast_Result_Accounts_06_View
-- Aggregating wrapper over 06_level2_view.
-- Not currently used; reserved for future Forecast rewrite.
-- Aggregates invoiced_quantity and invoice_value with SUM;
-- all other columns pass through and appear in GROUP BY.
-- WHERE (1=1) in original is trivially true — omitted here.
-- WITH (NOLOCK) is a SAP/MSSQL hint — not applicable in PostgreSQL.
-- final_invoice_number and final_invoice_exists from level2 view
-- are not exposed here (filtered to 'N' in level2, not needed above).
-- ============================================================

CREATE OR REPLACE VIEW public.forecast_result_accounts_06_view AS

SELECT
    l2.order_flag,
    l2.order_label,
    l2.allocation_reference,
    l2.allocation_company,
    l2.alliocation_pcentre,
    l2.allocation_commodity,
    l2.allocation_commodity_type,
    l2.allocation_date,
    l2.allocation_total_sales_quantity,
    l2.allocation_total_unfixed,
    l2.allocation_fixed_flag,
    l2.contno,
    l2.split,
    l2.priceterm,
    l2.record_date,
    l2.contract_client,
    l2.allocated_quantity,
    l2.price_curr_unit,
    l2.currency,
    l2.priceunit,
    l2.total_forecast,
    l2.total_forecast_base_curr,
    l2.invoice_heading,
    l2.invoice_order,
    l2.invoice_flag,
    l2.invoice_number,
    l2.invoice_date,
    l2.invoice_client,
    l2.invoice_text,
    SUM(l2.invoiced_quantity)                                          AS invoiced_quantity,
    l2.invoice_unit_price,
    l2.invoice_currency,
    l2.invoice_priceunit,
    SUM(l2.invoice_value)                                              AS invoice_value,
    l2.signed_invoice_value,
    l2.posted_date,
    l2.posted_invoice_value,
    l2.contract_type,
    l2.allocation_completed,
    l2.allocation_completed_date,
    l2.invoice_house_rate,
    l2.contract_currency_to_basecurr_conversion_factor,
    l2.stock_allocation_check,
    l2.manual_outb_expense_amount,
    l2.merged_line_splitter,
    l2.suggest_completed,
    l2.origin,
    l2.accperiod,
    l2.ledgernum,
    l2.linenum,
    l2.comments
FROM public.forecast_result_accounts_06_level2_view l2
GROUP BY
    l2.order_flag,
    l2.order_label,
    l2.allocation_reference,
    l2.allocation_company,
    l2.alliocation_pcentre,
    l2.allocation_commodity,
    l2.allocation_commodity_type,
    l2.allocation_date,
    l2.allocation_total_sales_quantity,
    l2.allocation_total_unfixed,
    l2.allocation_fixed_flag,
    l2.contno,
    l2.split,
    l2.priceterm,
    l2.record_date,
    l2.contract_client,
    l2.allocated_quantity,
    l2.price_curr_unit,
    l2.currency,
    l2.priceunit,
    l2.total_forecast,
    l2.total_forecast_base_curr,
    l2.invoice_heading,
    l2.invoice_order,
    l2.invoice_flag,
    l2.invoice_number,
    l2.invoice_date,
    l2.invoice_client,
    l2.invoice_text,
    l2.invoice_unit_price,
    l2.invoice_currency,
    l2.invoice_priceunit,
    l2.signed_invoice_value,
    l2.posted_date,
    l2.posted_invoice_value,
