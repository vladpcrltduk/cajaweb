-- Source: dba.Forecast_Result_Accounts_00_View
-- Master UNION view combining all 8 Forecast_Result_Accounts views.
-- Not currently used; reserved for future Forecast rewrite.
-- Each branch selects the same 51 columns; SELECT * cannot be used
-- uniformly because views 07 and 08 expose two extra columns
-- (final_invoice_number, final_invoice_exists) not present in 01–06.
-- Original used UNION (deduplicating); changed to UNION ALL here.
-- Each view draws from distinct source tables and order_flags, making
-- true duplicates impossible in practice. UNION would force a full
-- sort/hash across all rows for no benefit.
-- WITH (NOLOCK) SAP hint and WHERE (1=1) trivially-true predicates
-- from original omitted — both are no-ops in PostgreSQL.
-- ============================================================

